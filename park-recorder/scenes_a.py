"""A版本步骤（occupy_park 无车位号）。want 为按规格推测的值，只用于录制报告对比，写入用例的是实际返回。"""
from datetime import datetime, timedelta

from record import GATES, plates, rF, rS, scene

TEMP = 'E000:temp|null|active'
PWD = 'Abc123!'


def gates(r, wants=None):
    for i, g in enumerate(GATES):
        r.call('query_gate_status', g, want=wants[i] if wants else None)


@scene('test_cjl_a1_temp_cap_500_release_paths')
def _(r):
    cars = r.enter(plates('S', 1, 500), park=True)
    r.status('S00001', cars[0][0], 'parked')
    r.status('S00500', cars[499][0], 'parked')
    r.entry('S00501', 'G1', want=rF)
    r.time_pass('sec', 5)
    r.status('S00501', None, 'outpark')
    mid = r.member('13900000001')
    r.call('bind_plate_id', mid, 'M00001', want=rS)
    vip = r.entry('M00001', 'G2')
    r.time_pass('sec', 5)
    r.status('M00001', vip[0], 'inpark')
    r.occupy(vip[0])
    for (sid, _), gate in zip(cars[:2], ('G1', 'G2')):
        r.release(sid)
        r.exit(sid, gate)
    r.time_pass('sec', 5)
    r.status('S00001', None, 'outpark')
    r.status('S00002', None, 'outpark')
    r.call('query_account', cars[0][1], want=rF)
    r.call('query_account', cars[2][1], want=TEMP)
    r.call('change_gate', 'G3', 'B', want=rS)
    r.entry('S00502', 'G3')
    r.time_pass('sec', 5)
    r.status('S00502', None, 'outpark')
    r.call('change_gate', 'G3', 'IO', want=rS)
    back = r.enter(['S00503', 'S00504', 'S00505'])
    r.status('S00503', back[0][0], 'inpark')
    r.status('S00504', back[1][0], 'inpark')
    r.status('S00505', None, 'outpark')


