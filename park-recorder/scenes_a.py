    r.call('query_account', c503, want='E000:member|13900000503|active')
    r.register('13900000504', PWD, want=rF)
    r.register('13900000001', PWD)
    r.goto(datetime(2026, 1, 1, 23, 59, 59))
    r.call('query_account', c501, want='E000:member|13900000501|expired')
    r.time_pass('sec', 1)
    r.call('query_account', c501, want=rF)
